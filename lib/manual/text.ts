export type TextKey = keyof typeof TEXT;

const translated = extra as Record<string, { ja?: string; zh?: string }>;

/** A text in a language: its own, else English (Korean when even that is missing). */
export function pick(key: string, lang: Lang, vars?: Record<string, string | number>): string {
  const t = (TEXT as Record<string, T>)[key];
  if (!t) return key;
  const own = lang === "ko" ? t.ko : lang === "en" ? t.en : (translated[key]?.[lang] ?? t[lang]);
  let s = own || t.en || t.ko;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
